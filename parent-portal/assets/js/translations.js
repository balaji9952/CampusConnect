export function getLang() {
  return localStorage.getItem('lang') || 'en';
}

export function setLang(l) {
  localStorage.setItem('lang', l);
}

export function t(key) {
  const lang = getLang();
  return T[lang]?.[key] || T['en'][key] || key;
}

export function applyLang() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('select option[data-i18n]').forEach(opt => {
    opt.textContent = t(opt.getAttribute('data-i18n'));
  });
  
  // Specific element mappings can be done safely using optional chaining
  const setEl = (id, val) => { const e = document.getElementById(id); if (e) e.textContent = val; };
  setEl('w-tagline', t('w_tagline'));
  setEl('w-title', t('w_title'));
  setEl('w-sub', t('w_sub'));
  setEl('btn-google-lbl', t('btn_google_lbl'));
  setEl('btn-google-sub', t('btn_google_sub'));
  setEl('pv-lang', t('lang_name'));
}

export function initLanguageSelection() {
  applyLang();
}
